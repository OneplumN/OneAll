import assert from 'node:assert/strict';
import test from 'node:test';

import {
  compileIpRegexFromText,
  expandIpRegex,
  isValidIpv4,
  parseIpLines,
  testIpAgainstRegex
} from '../src/ipRegexTool.ts';

test('validates IPv4 addresses strictly', () => {
  assert.equal(isValidIpv4('192.168.1.1'), true);
  assert.equal(isValidIpv4('10.0.0.255'), true);
  assert.equal(isValidIpv4('256.1.1.1'), false);
  assert.equal(isValidIpv4('10.0.0'), false);
  assert.equal(isValidIpv4('10.0.0.1/24'), false);
});

test('parses non-empty IP lines', () => {
  assert.deepEqual(parseIpLines('192.168.1.1\n\n 10.0.0.1,10.0.0.2；10.0.0.3 '), ['192.168.1.1', '10.0.0.1', '10.0.0.2', '10.0.0.3']);
});

test('compiles unique valid IPs into the legacy compressed regex', () => {
  const result = compileIpRegexFromText('192.168.1.1\n192.168.1.1\n10.0.0.5\nbad');

  assert.equal(result.regex, '(192\\.168\\.1\\.1)|(10\\.0\\.0\\.5)');
  assert.equal(result.matchedCount, 2);
  assert.equal(result.duplicateCount, 1);
  assert.deepEqual(result.invalidIps, ['bad']);
  assert.deepEqual(result.normalizedIps, ['192.168.1.1', '10.0.0.5']);
});

test('compresses adjacent octets like the legacy platform script', () => {
  const result = compileIpRegexFromText('10.193.2.52\n10.193.2.53\n10.193.2.54\n10.193.2.108\n10.193.74.100\n10.193.74.101\n10.193.74.52');

  assert.equal(result.regex, '(10\\.193\\.(2\\.(108|5[2-4])|74\\.(10[0-1]|52)))');
});

test('expands regex generated by the helper', () => {
  const result = expandIpRegex('(192\\.168\\.1\\.1)|(10\\.0\\.0\\.5)', 10);

  assert.deepEqual(result.ips, ['10.0.0.5', '192.168.1.1']);
  assert.equal(result.count, 2);
  assert.equal(result.truncated, false);
});

test('rejects unsupported arbitrary regex expansion', () => {
  assert.throws(() => expandIpRegex('^10\\.0\\.0\\..*$'), /不支持包含重复量词/);
});

test('tests an IP against a generated regex', () => {
  assert.deepEqual(testIpAgainstRegex('10.0.0.5', '^(192\\.168\\.1\\.1|10\\.0\\.0\\.5)$'), {
    matched: true,
    validIp: true,
    error: ''
  });
  assert.equal(testIpAgainstRegex('10.0.0.6', '^(192\\.168\\.1\\.1|10\\.0\\.0\\.5)$').matched, false);
  assert.equal(testIpAgainstRegex('999.0.0.1', '^(10\\.0\\.0\\.5)$').validIp, false);
});
